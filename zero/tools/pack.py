#!/usr/bin/env python3
"""Pack zero/src/art/**/*.png into zero/src/art/sheets.ts as data URLs so the single-file build carries them."""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'src/art'
lines = ['// Generated by zero/tools/pack.py from the PNG sheets beside this file. Do not edit.',
         'const sheets: Record<string, string> = {']
for p in sorted(root.rglob('*.png')):
    key = p.relative_to(root).with_suffix('').as_posix()
    lines.append(f"  '{key}': 'data:image/png;base64,{base64.b64encode(p.read_bytes()).decode()}',")
lines += ['};', 'export default sheets;', '']
(root / 'sheets.ts').write_text('\n'.join(lines))
print('packed', len(lines) - 4, 'sheets')
