#!/usr/bin/env python3
"""Build css/prism-icons.css from the Prism UI icon sheet (src/art/prism/ui/icons.png, drawn in
Pixelwright). Dock icons replace the glyphs on .dock-btn by data-id; resource icons are recoloured
from their magenta team shades to each resource's colour (packs/core) and replace the .res glyphs.
Turn off with body.no-prism-icons. Run after changing the sheet or a resource colour."""
import base64, io, json, pathlib
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
art = root / 'src/art/prism/ui'
meta = json.loads((art / 'icons.json').read_text())
sheet = Image.open(art / 'icons.png').convert('RGBA')
TEAM = [(0x80, 0, 0x80), (0xc0, 0, 0xc0), (0xff, 0, 0xff)]
colors = {}
for f in sorted((root / 'packs/core').glob('*.json')):
    d = json.loads(f.read_text()); r = d.get('resources')
    for x in (r.values() if isinstance(r, dict) else r or []):
        if isinstance(x, dict) and x.get('id') and x.get('color'): colors[x['id']] = x['color']
def url(im):
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()
def tint(im, hexc):
    v = int(hexc[1:], 16); rgb = ((v >> 16) & 255, (v >> 8) & 255, v & 255)
    ramp = [tuple(max(0, min(255, round(c * k))) for c in rgb) for k in (0.45, 0.8, 1.12)]
    out = im.copy(); px = out.load()
    for y in range(out.height):
        for x in range(out.width):
            p = px[x, y]
            if p[3] and p[:3] in TEAM: px[x, y] = ramp[TEAM.index(p[:3])] + (255,)
    return out
sheet2 = Image.open(art / 'icons2.png').convert('RGBA')
icon = lambda row, i: sheet.crop((i * 12, row * 12, i * 12 + 12, row * 12 + 12))
sheet3 = Image.open(art / 'icons3.png').convert('RGBA')
strip = lambda im, i: im.crop((i * 12, 0, i * 12 + 12, 12))
dock = [(k, icon(0, i)) for i, k in enumerate(meta['dock'])] + [(k, strip(sheet2, i)) for i, k in enumerate(meta.get('dock2', []))] \
     + [(k, strip(sheet3, i)) for i, k in enumerate(meta.get('dock3', []))]
G = 'body:not(.no-prism-icons)'
# only ids that have an icon lose their glyph, so a new dock entry or resource keeps its text icon
D = ', '.join(f'{G} .dock-btn[data-id="{k}"] > span' for k, _ in dock)
R = ', '.join(f'{G} .res[data-id="{"exchange" if k == "crypto" else k}"] .ri' for k in meta['res'])
css = ['/* Generated by tools/prism-icons.py from src/art/prism/ui/icons.png. Do not edit. */',
       f"{D}, {R} {{ font-size: 0 !important; display: inline-block; background: center / 100% 100% no-repeat; image-rendering: pixelated; }}",
       f"{D} {{ width: 24px; height: 24px; margin-bottom: 1px; }}",
       f"{R} {{ width: 24px; height: 24px; vertical-align: -5px; filter: drop-shadow(0 0 3px rgba(0,0,0,.6)); }}",
       f"{G} .hud-res.compact .res .ri {{ width: 12px; height: 12px; vertical-align: -1px; }}"]
for k, im in dock:
    css.append(f"{G} .dock-btn[data-id=\"{k}\"] > span {{ background-image: url({url(im)}); }}")
for i, k in enumerate(meta['res']):
    sel = 'exchange' if k == 'crypto' else k
    css.append(f"{G} .res[data-id=\"{sel}\"] .ri {{ background-image: url({url(tint(icon(1, i), colors.get(k, '#7cf4da')))}); }}")
(root / 'css/prism-icons.css').write_text('\n'.join(css) + '\n')
print('wrote', len(dock), 'dock and', len(meta['res']), 'resource icons')
