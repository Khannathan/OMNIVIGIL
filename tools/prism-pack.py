#!/usr/bin/env python3
"""Pack the Prism sprite sheets (src/art/prism/**/*.png) into src/art/prism/sheets.ts as data URLs,
so the single-file artifact build carries them. Run after replacing any sheet."""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'src/art/prism'
lines = ['// Generated by tools/prism-pack.py from the PNG sheets beside this file. Do not edit.',
         'const sheets: Record<string, string> = {']
for p in sorted(root.rglob('*.png')):
    if p.relative_to(root).parts[0] == 'ui': continue  # UI icons go to css/prism-icons.css
    key = p.relative_to(root).with_suffix('').as_posix()
    lines.append(f"  '{key}': 'data:image/png;base64,{base64.b64encode(p.read_bytes()).decode()}',")
lines += ['};', 'export default sheets;', '']
(root / 'sheets.ts').write_text('\n'.join(lines))
print('packed', len(lines) - 5, 'sheets')
